minutes = 145
hours = minutes // 60       # Whole hours
rem_mins = minutes % 60     # Remaining minutes
power_val = 2 ** 5          # 2 raised to 5

print(f"{minutes} mins = {hours}h {rem_mins}m | 2^5 = {power_val}")